// Simplified IEEE 754 Single Precision Floating Point Adder
// Implements FADD.S and FSUB.S

// lab requirements:
// - No overflow / underflow handling
// - No NaN / Infinity handling
// - Round to nearest, ties to even
// - Assumes inputs are nomal numbers

module FP_Adder(
    input  logic [31:0] a,
    input  logic [31:0] b,
    input  logic        sub,    // 0: add, 1: subtract
    output logic [31:0] result 
);

//==================================================================================
// Step1: Extract Components
//==================================================================================
logic        a_sign, b_sign;
logic [7:0]  a_exp, b_exp;
logic [23:0] a_mant, b_mant;     // mantissa

assign a_sign = a[31];
assign a_exp  = a[30:23];
assign a_mant = a[22:0];

assign b_sign = b[31];
assign b_exp  = b[30:23];
assign b_mant = b[22:0];

// Add implicit leading 1 (normalized mantissa: 1.mantissa)
logic [23:0] a_mant_full, b_mant_full;
assign a_mant_full = {1'b1, a_mant};
assign b_mant_full = {1'b1, b_mant};

// Handle subtraction: flip b's sign
logic b_sign_effective;
assign b_sign_effective = sub ? ~b_sign : b_sign;


//==================================================================================
// Step2: Align Exponents
//==================================================================================
// Find larger exp
logic [7:0] exp_diff;
logic a_larger;

assign a_larger = (a_exp >= b_exp);
assign exp_diff = a_larger ? (a_exp - b_exp) : (b_exp - a_exp);

logic [7:0] result_exp;
assign result_exp = a_larger ? a_exp : b_exp;

// Align mantissa by shifting smaller one right
logic [49:0] a_mant_aligned, b_mant_aligned;

always_comb begin
    if (a_larger) begin
        // shift b right
        a_mant_aligned = {a_mant_full, 26'b0};
        b_mant_aligned = {b_mant_full, 26'b0} >> exp_diff;
    end
    else begin
        // shift a right
        a_mant_aligned = {a_mant_full, 26'b0} >> exp_diff;
        b_mant_aligned = {b_mant_full, 26'b0};
    end
end
/* Why concat 26 bit behind? */
// - *_mant_full is 24 bit, so there must be 24 bit in order to keep the right shift
// - And the two more bit is for guard bit and round bit
//      - Guard bit: for rounding precision
//      - Round bit: for rounding decision



//==================================================================================
// Step3: A(dd or Subtract Mantissas
//==================================================================================
logic [50:0] sum_mant;      // 50 bit + 50 bit => 51 bit
logic sum_sign;

always_comb begin
    if (a_sign == b_sign_effective) begin
        // Same sign: add magnitudes
        sum_mant = a_mant_aligned + b_mant_aligned;
    end
    else begin
        if (a_mant_aligned >= b_mant_aligned) begin
            sum_mant = a_mant_aligned - b_mant_aligned;
            sum_sign = a_sign;
        end
        else begin
            sum_mant = b_mant_aligned - a_mant_aligned;
            sum_sign = b_sign_effective;
        end
    end
end


