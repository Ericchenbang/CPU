// Normalize: shift mantissa left, decrease exponent
always_comb begin
    if (sum_mant == 51'b0) begin
        // Result is zero
        norm_exp = 8'b0;
        norm_mant = 50'b0;
    end
    else if (leading_zeros == 0) begin
        // Already normalized (overflow case)
        // Shift right 1, increment exponent
        norm_exp = result_exp + 1;
        norm_mant = sum_mant >> 1;
    end
    else begin
        // Shift left to normalize
        norm_exp = result_exp - leading_zeros + 1;
        norm_mant = sum_mant << leading_zeros;
    end
end

//==================================================================================
// Step5: Round to nearest, ties to even
//==================================================================================

// norm_mant format: [49:26] = integer part, [35:0] = fractional part
// We want: [49:27] = mantissa (23 bits), [26] = round bit, [25:0] = sticky bits

logic [22:0] final_mant;
logic round_bit;
logic sticky_bit;
logic [7:0] final_exp;

assign round_bit = norm_mant[26];
assign sticky_bit = |norm_mant[25:0];

logic round_up;
always_comb begin
    if (round_bit == 1'b0) begin
        round_up = 1'b0;
    end
    else if (sticky_bit == 1'b1) begin
        // More than halfway
        round_up = 1'b1;    
    end
    else begin
        // Ties, check LSB of mantissa is odd or not
        round_up = norm_mant[27];
    end
end

//==================================================================================
// Step6: Pack result
//==================================================================================
always_comb begin
    if (sum_mant == 51'b0) begin
        // Result is zero: +0.0
        result = 32'h0000_0000;
    end
    else begin
        result = {sum_sign, final_exp, final_mant};
    end
end


endmodule