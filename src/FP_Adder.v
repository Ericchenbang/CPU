        51'b00_1???_????_????_????_????_????_????_????_????_????_????_????:
            leading_zeros = 2;
        51'b00_01??_????_????_????_????_????_????_????_????_????_????_????:
            leading_zeros = 3;
        51'b00_001?_????_????_????_????_????_????_????_????_????_????_????:
